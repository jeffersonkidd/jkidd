// pnpm tokens: sources/*.json → src/tokens.css + src/tokens.gen.ts
// The Pipeline postcard's sample ("Figma variables → pnpm tokens → tokens.css") is this script.

import { writeFileSync } from "node:fs";
import { palette, tokens, SCHEMES, POST_TYPES, GENRES, root } from "./lib/tokens.mjs";
import { kebab } from "./lib/color.mjs";

const HEADER = `/* GENERATED by scripts/build-tokens.mjs from sources/jkxo-tertiary.json and sources/jkidd.tokens.json.
   Don't edit by hand: change the JSON and run \`pnpm tokens\`. Figma: ${tokens.figma.fileName} (${tokens.figma.fileKey}). */`;

const decl = (entries, indent = "  ") => entries.map(([k, v]) => `${indent}${k}: ${v};`).join("\n");

// Palette collection: 5 tonal palettes × 18 tones = 90 variables.
const paletteVars = Object.entries(palette.palettes).flatMap(([name, tones]) =>
  Object.entries(tones).map(([tone, hex]) => [`--jk-palette-${name}-${tone}`, hex.toLowerCase()]),
);

const fontVars = Object.entries(tokens.fonts)
  .filter(([k]) => !k.startsWith("$"))
  .map(([k, f]) => [`--jk-font-${k}`, `"${f.family}", ${f.fallback}`]);

// Genres: their own colours, not the palette's (POSTCARDS.md §4). Scheme-independent.
const genreVars = Object.entries(GENRES).flatMap(([g, def]) => [
  ...Object.entries(def.colors).map(([k, hex]) => [`--jk-genre-${g}-${kebab(k)}`, hex.toLowerCase()]),
  ...Object.entries(def.ribbons).flatMap(([k, r]) => [
    [`--jk-genre-${g}-ribbon-${k}`, r.fill.toLowerCase()],
    [`--jk-genre-${g}-on-ribbon-${k}`, `var(--jk-genre-${g}-${kebab(r.on)})`],
  ]),
]);

// Named by the Figma variable's code syntax, so space/400 becomes --jk-space-4 as in Figma.
const layoutVars = Object.entries(tokens.layout).map(([k, t]) => [t.figma ?? `--jk-${kebab(k)}`, `${t.value}${t.unit}`]);

// Effect styles → box-shadow lists. Elevation/Card becomes --jk-elevation-card.
const effectVars = Object.entries(tokens.effects)
  .filter(([k]) => !k.startsWith("$"))
  .map(([name, shadows]) => [
    `--jk-${kebab(name.replace("/", "-"))}`,
    shadows.map((s) => `${s.x}px ${s.y}px ${s.blur}px ${s.spread}px ${s.color}`).join(", "),
  ]);

// Scheme collection: 49 roles × 6 modes. Light is also the :root fallback.
const schemeBlock = (mode) => {
  const sel = mode === "light" ? `:root,\n[data-scheme="light"]` : `[data-scheme="${mode}"]`;
  const roles = Object.entries(palette.schemes[mode]).map(([role, hex]) => [
    `--md-sys-color-${kebab(role)}`,
    hex.toLowerCase(),
  ]);
  const cs = mode.startsWith("dark") ? "dark" : "light";
  return `${sel} {\n  color-scheme: ${cs};\n${decl(roles)}\n}`;
};

// Post Type collection: aliases into the scheme. Re-declared under any nested
// [data-scheme] so a type set on an ancestor resolves against the inner scheme.
const typeBlock = ([type, t]) => {
  const v = (role) => `var(--md-sys-color-${kebab(role)})`;
  return `[data-post-type="${type}"],\n[data-post-type="${type}"] [data-scheme] {\n${decl([
    ["--jk-type-accent", v(t.accent)],
    ["--jk-type-ink", v(t.ink)],
    ["--jk-type-on-accent", v(t.onAccent)],
    ["--jk-type-label", `"${t.label}"`],
  ])}\n}`;
};

// Text styles → utility classes. Figma letter spacing is percent → em.
const textStyles = Object.entries(tokens.textStyles)
  .filter(([k]) => !k.startsWith("$"))
  .map(([name, s]) => {
    const cls = `.jk-text-${kebab(name.replace("/", "-")).replace(/\s+/g, "-")}`;
    const props = [
      ["font-family", `var(--jk-font-${s.font})`],
      ["font-weight", s.weight],
      ["font-size", `${s.size}px`],
      ["line-height", s.lineHeight],
      ["letter-spacing", `${s.letterSpacing / 100}em`],
    ];
    if (s.uppercase) props.push(["text-transform", "uppercase"]);
    return `/* ${name} */\n${cls} {\n${decl(props)}\n}`;
  });

const css = [
  HEADER,
  `:root {\n  /* Palette: ${paletteVars.length} variables */\n${decl(paletteVars)}\n\n  /* Type */\n${decl(fontVars)}\n\n  /* Layout */\n${decl(layoutVars)}\n\n  /* Effects */\n${decl(effectVars)}\n\n  /* Genres */\n${decl(genreVars)}\n}`,
  ...SCHEMES.map(schemeBlock),
  ...Object.entries(POST_TYPES).map(typeBlock),
  ...textStyles,
].join("\n\n");

writeFileSync(`${root}src/tokens.css`, css + "\n");

// Typed mirror for components and the Studio app.
const canvas = Object.fromEntries(
  Object.entries(tokens.canvas).filter(([k]) => !k.startsWith("$")).map(([k, c]) => [k, { width: c.width, height: c.height, figma: c.figma }]),
);
const ts = `// GENERATED by scripts/build-tokens.mjs. Don't edit by hand.

export const FIGMA_FILE_KEY = ${JSON.stringify(tokens.figma.fileKey)};

export const SCHEMES = ${JSON.stringify(SCHEMES)} as const;
export type Scheme = (typeof SCHEMES)[number];

export const POST_TYPES = ${JSON.stringify(Object.keys(POST_TYPES))} as const;
export type PostType = (typeof POST_TYPES)[number];

export const POST_TYPE_TOKENS: Record<PostType, { label: string; accent: string; ink: string; onAccent: string }> = ${JSON.stringify(POST_TYPES, null, 2)};

export const CANVAS = ${JSON.stringify(canvas, null, 2)} as const;
export type Ratio = keyof typeof CANVAS;

export const GENRE_RIBBONS = ${JSON.stringify(Object.fromEntries(Object.entries(GENRES).map(([g, d]) => [g, Object.keys(d.ribbons)])))} as const;

export const SCHEME_COLORS: Record<Scheme, Record<string, string>> = ${JSON.stringify(palette.schemes, null, 2)};

export const PALETTES: Record<string, Record<string, string>> = ${JSON.stringify(palette.palettes, null, 2)};
`;
writeFileSync(`${root}src/tokens.gen.ts`, ts);

const roleCount = Object.keys(palette.schemes.light).length;
console.log(
  `tokens: ${paletteVars.length} palette vars · ${roleCount} scheme roles × ${SCHEMES.length} modes · ${Object.keys(POST_TYPES).length} post types · ${textStyles.length} text styles → src/tokens.css, src/tokens.gen.ts`,
);
